//! "Ask first" Codex turns over `codex app-server`. `codex exec` cannot answer approval
//! callbacks, so this runner speaks the app-server protocol: the installed CLI must generate the
//! approval schemas and complete `initialize` before any model turn starts. Command and file
//! approvals go to the Gatekeeper panel; every reply is written once, after the journal confirms
//! it is still current. Anything the adapters cannot represent is declined, never approved.
use crate::approvals::Approvals;
use crate::models::{AccessMode, Activity, Provider};
use crate::providers::{self, Invocation};
use lumen_gatekeeper::{support, Availability, Provider as Engine, Scope};
use serde_json::{json, Value};
use std::path::Path;
use std::time::Duration;
use tokio::io::{AsyncBufReadExt, AsyncWriteExt, BufReader};
use tokio::sync::{mpsc, watch};

const STEP_TIMEOUT: Duration = Duration::from_secs(60);
/// A protocol line longer than this is treated as a broken connection.
const MAX_LINE: usize = 8 * 1024 * 1024;

const OBSERVED: &[&str] = &[
    "item/started",
    "item/fileChange/patchUpdated",
    "item/completed",
    "serverRequest/resolved",
    "turn/completed",
];

async fn version(config: &Path) -> Result<String, String> {
    let mut c = providers::command(&Provider::Gpt)?;
    providers::isolate(&mut c, &Provider::Gpt, config);
    c.arg("--version")
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .kill_on_drop(true);
    let out = tokio::time::timeout(Duration::from_secs(20), c.output())
        .await
        .map_err(|_| "unavailable: codex --version timed out")?
        .map_err(|e| format!("unavailable: {e}"))?;
    let v = String::from_utf8_lossy(&out.stdout).trim().to_string();
    if v.is_empty() {
        return Err("unavailable: Codex did not report a version".into());
    }
    Ok(v)
}

/// Schemas generated by the selected binary, the evidence `support::codex` checks.
async fn schemas(config: &Path) -> Result<(Value, Value, Value), String> {
    let dir = std::env::temp_dir().join(format!("lumen-codex-schema-{}", uuid::Uuid::new_v4()));
    let mut c = providers::command(&Provider::Gpt)?;
    providers::isolate(&mut c, &Provider::Gpt, config);
    c.args(["app-server", "generate-json-schema", "--out"])
        .arg(&dir)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .kill_on_drop(true);
    let status = tokio::time::timeout(STEP_TIMEOUT, c.status())
        .await
        .map_err(|_| "unavailable: Codex schema generation timed out")?
        .map_err(|e| format!("unavailable: {e}"))?;
    let read = |name: &str| -> Value {
        std::fs::read_to_string(dir.join(name))
            .ok()
            .and_then(|t| serde_json::from_str(&t).ok())
            .unwrap_or(Value::Null)
    };
    let out = (
        read("ServerRequest.json"),
        read("CommandExecutionRequestApprovalResponse.json"),
        read("FileChangeRequestApprovalResponse.json"),
    );
    let _ = std::fs::remove_dir_all(&dir);
    if !status.success() {
        return Err("unavailable: Codex could not generate its app-server schema".into());
    }
    Ok(out)
}

async fn cached_schemas(config: &Path, version: &str) -> Result<(Value, Value, Value), String> {
    type Evidence = (Value, Value, Value);
    static CACHE: std::sync::OnceLock<
        tokio::sync::Mutex<std::collections::HashMap<String, Evidence>>,
    > = std::sync::OnceLock::new();
    let mut cache = CACHE.get_or_init(Default::default).lock().await;
    if let Some(evidence) = cache.get(version) {
        return Ok(evidence.clone());
    }
    let evidence = schemas(config).await?;
    cache.insert(version.to_owned(), evidence.clone());
    Ok(evidence)
}

struct Wire {
    lines: tokio::io::Lines<BufReader<tokio::process::ChildStdout>>,
    out: mpsc::Sender<Value>,
    next: u64,
}

impl Wire {
    async fn send(&mut self, method: &str, params: Value) -> Result<u64, String> {
        self.next += 1;
        let msg = json!({"id": self.next, "method": method, "params": params});
        self.out
            .send(msg)
            .await
            .map_err(|_| "Codex closed its input")?;
        Ok(self.next)
    }

    async fn read(&mut self) -> Result<Option<Value>, String> {
        loop {
            let Some(line) = self.lines.next_line().await.map_err(|e| e.to_string())? else {
                return Ok(None);
            };
            if line.len() > MAX_LINE {
                return Err("Codex sent an oversized protocol message".into());
            }
            if let Ok(v) = serde_json::from_str::<Value>(&line) {
                return Ok(Some(v));
            }
        }
    }
}

fn is_response(v: &Value, id: u64) -> bool {
    v.get("method").is_none() && v["id"].as_u64() == Some(id)
}

fn decline(id: &Value) -> Value {
    json!({"id": id, "result": {"decision": "decline"}})
}

/// Normal activities for the chat, the same kinds the headless runner emits.
fn activity(v: &Value, text: &mut String, emit: &mut impl FnMut(Activity)) {
    let mut push = |kind: &str, t: String| {
        emit(Activity {
            kind: kind.into(),
            text: t,
        })
    };
    match v["method"].as_str().unwrap_or("") {
        "item/started" => {
            let item = &v["params"]["item"];
            if ["commandExecution", "mcpToolCall", "fileChange"]
                .contains(&item["type"].as_str().unwrap_or(""))
            {
                if let Some(id) = item["id"].as_str() {
                    push("tool-start", json!({"id":id}).to_string());
                }
            }
        }
        "thread/tokenUsage/updated" => {
            let usage = &v["params"]["tokenUsage"];
            if let Some(input) = usage["last"]["inputTokens"].as_u64() {
                push("usage", input.to_string());
            }
            if let Some(window) = usage["modelContextWindow"].as_u64() {
                push("window", window.to_string());
            }
        }
        "item/agentMessage/delta" => {
            if let Some(d) = v["params"]["delta"].as_str() {
                text.push_str(d);
                push("delta", d.into());
            }
        }
        "item/completed" => {
            let item = &v["params"]["item"];
            if ["commandExecution", "mcpToolCall", "fileChange"]
                .contains(&item["type"].as_str().unwrap_or(""))
            {
                if let Some(id) = item["id"].as_str() {
                    push("tool-end", json!({"id":id}).to_string());
                }
            }
            match item["type"].as_str().unwrap_or("") {
                "agentMessage" => {
                    if let Some(t) = item["text"].as_str() {
                        *text = t.to_string();
                        push("replace", t.into());
                    }
                }
                "commandExecution" => push(
                    "tool",
                    format!(
                        "{}\n{}",
                        item["command"].as_str().unwrap_or("Command"),
                        item["aggregatedOutput"].as_str().unwrap_or("")
                    ),
                ),
                "fileChange" => push("file", item["changes"].to_string()),
                "mcpToolCall" => push("tool", item["tool"].as_str().unwrap_or("Tool").into()),
                "imageGeneration" | "imageView" => {
                    if let Some(path) = item["savedPath"].as_str().or(item["path"].as_str()) {
                        push("image", path.into());
                    }
                }
                "collabAgentToolCall" => {
                    if let Some(agents) = item["agentsStates"].as_object() {
                        for (id, agent) in agents {
                            push("child",json!({"id":id,"kind":"status","text":"","status":agent["status"],"tool":item["tool"],"sessionId":id}).to_string());
                            if let Some(message)=agent["message"].as_str().filter(|s|!s.is_empty()) {
                                push("child",json!({"id":id,"kind":"message","text":message,"sessionId":id}).to_string());
                            }
                        }
                    }
                }
                "subAgentActivity" => push("child",json!({"id":item["agentThreadId"],"kind":"status","text":item["agentPath"].as_str().unwrap_or(""),"status":item["kind"]}).to_string()),
                "reasoning" => {
                    let summary = item["summary"]
                        .as_array()
                        .map(|a| {
                            a.iter()
                                .filter_map(|s| s.as_str())
                                .collect::<Vec<_>>()
                                .join("\n")
                        })
                        .unwrap_or_default();
                    if !summary.is_empty() {
                        push("thinking", summary);
                    }
                }
                _ => {}
            }
        }
        "error" => push(
            "error",
            v["params"]["error"]["message"]
                .as_str()
                .unwrap_or("Codex reported an error")
                .into(),
        ),
        _ => {}
    }
}

/// Writes queued messages; approval replies are checked against the journal right before.
async fn writer(
    mut stdin: tokio::process::ChildStdin,
    mut queue: mpsc::Receiver<Value>,
    mut deliveries: mpsc::Receiver<lumen_gatekeeper::Delivery>,
    approvals: Approvals,
    failed: watch::Sender<bool>,
) {
    loop {
        let (line, delivery) = tokio::select! {
            m = queue.recv() => match m { Some(m) => (m, None), None => break },
            d = deliveries.recv() => match d {
                Some(d) => {
                    if !approvals.keeper.delivery_is_current(&d).unwrap_or(false) {
                        continue;
                    }
                    (d.response.clone(), Some(d))
                }
                None => break,
            },
        };
        let ok = stdin
            .write_all(format!("{line}\n").as_bytes())
            .await
            .is_ok()
            && stdin.flush().await.is_ok();
        if let Some(d) = delivery {
            let recorded = approvals.keeper.complete_delivery(&d, ok).is_ok();
            if !ok || !recorded {
                let _ = failed.send(true);
            }
        } else if !ok {
            let _ = failed.send(true);
        }
    }
}

pub async fn codex_turn(
    input: Invocation<'_>,
    approvals: Approvals,
    mut cancel: watch::Receiver<bool>,
    mut emit: impl FnMut(Activity),
) -> Result<String, String> {
    crate::execution::signal(&mut emit, "adapter-start");
    let cwd = dunce::canonicalize(input.workspace)
        .map_err(|_| "The conversation folder is no longer available")?;
    let version = version(input.config).await?;
    crate::execution::signal(&mut emit, "version-ready");
    let (requests, command_reply, file_reply) = cached_schemas(input.config, &version).await?;
    crate::execution::signal(&mut emit, "schema-ready");

    let mut c = providers::command(&Provider::Gpt)?;
    providers::isolate(&mut c, &Provider::Gpt, input.config);
    c.current_dir(&cwd)
        .args(support::codex_args())
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .kill_on_drop(true);
    if let Some(data) = input.config.parent().and_then(Path::parent) {
        let (extra, _) = crate::integrations::args(data, &Provider::Gpt)?;
        c.args(extra);
        if providers::graph_enabled(data) {
            if let Some(extra) = crate::graph_mcp::cli_args(data, &cwd, &Provider::Gpt) {
                c.args(extra);
            }
        }
    }
    if cfg!(windows) {
        c.args(["-c", "windows.sandbox=\"unelevated\""]);
    }
    if let Some(browser) = input.browser {
        browser.env(&mut c);
        let mut args = Vec::new();
        browser.args(&mut args, &Provider::Gpt)?;
        c.args(args);
    }
    crate::execution::signal(&mut emit, "spawn-start");
    let mut child = c
        .spawn()
        .map_err(|e| format!("unavailable: cannot start Codex: {e}"))?;
    crate::execution::signal(&mut emit, "process-started");
    if let Some(pid) = child.id() {
        emit(Activity {
            kind: "pid".into(),
            text: pid.to_string(),
        });
    }
    let stdin = child.stdin.take().ok_or("No input stream")?;
    let stdout = child.stdout.take().ok_or("No output stream")?;
    let (queue, queued) = mpsc::channel::<Value>(64);
    let (deliver, deliveries) = mpsc::channel(64);
    let (failed_tx, mut failed) = watch::channel(false);
    let writing = tokio::spawn(writer(
        stdin,
        queued,
        deliveries,
        approvals.clone(),
        failed_tx,
    ));
    let mut wire = Wire {
        lines: BufReader::new(stdout).lines(),
        out: queue,
        next: 0,
    };
    let mut scope: Option<Scope> = None;
    let outcome = run(
        &mut wire,
        &input,
        &approvals,
        &cwd,
        &version,
        (&requests, &command_reply, &file_reply),
        &deliver,
        &mut scope,
        &mut cancel,
        &mut failed,
        &mut emit,
    )
    .await;
    if let Some(scope) = &scope {
        let _ = approvals.keeper.disconnect(scope, "Codex turn finished");
    }
    drop(wire);
    drop(deliver);
    providers::terminate(&mut child).await;
    writing.abort();
    outcome
}

#[allow(clippy::too_many_arguments)]
async fn run(
    wire: &mut Wire,
    input: &Invocation<'_>,
    approvals: &Approvals,
    cwd: &Path,
    version: &str,
    evidence: (&Value, &Value, &Value),
    deliver: &mpsc::Sender<lumen_gatekeeper::Delivery>,
    scope: &mut Option<Scope>,
    cancel: &mut watch::Receiver<bool>,
    failed: &mut watch::Receiver<bool>,
    emit: &mut impl FnMut(Activity),
) -> Result<String, String> {
    // 1. initialize: support is decided from this run's real answers, not the version string.
    let id = wire
        .send(
            "initialize",
            json!({"clientInfo": {"name": "lumen", "version": env!("CARGO_PKG_VERSION")},"capabilities":{"experimentalApi":true}}),
        )
        .await?;
    let init = expect(wire, id).await?;
    crate::execution::signal(emit, "protocol-ready");
    let availability = support::codex(version, evidence.0, evidence.1, evidence.2, &init);
    if let Availability::Unavailable { reason } = &availability {
        return Err(format!("unavailable: {reason}"));
    }
    wire.out
        .send(json!({"method": "initialized"}))
        .await
        .map_err(|_| "Codex closed its input")?;

    // Native resumes retain tool exchanges, project instructions and agent state.
    let mut params = support::codex_thread_params(&cwd.to_string_lossy());
    params["approvalPolicy"] = json!(if input.access == AccessMode::Ask {
        "on-request"
    } else {
        "never"
    });
    params["sandbox"] = json!(match input.access {
        AccessMode::Autopilot => "danger-full-access",
        AccessMode::FileEdits => "workspace-write",
        _ => "read-only",
    });
    if let Some(model) = input.model {
        params["model"] = json!(model);
    }
    let method = if let Some(session) = input.resume {
        params["threadId"] = json!(session);
        "thread/resume"
    } else {
        params["dynamicTools"] = json!([{
            "type":"function","name":"lumen_request_user_input",
            "description":"Ask clear questions with selectable options in the Lumen UI when a missing user decision changes the result. This collects information, not permission. Use without changing to plan mode. The user can also write a custom answer.",
            "inputSchema":{"type":"object","properties":{"questions":{"type":"array","minItems":1,"maxItems":6,"items":{"type":"object","properties":{"id":{"type":"string"},"header":{"type":"string"},"question":{"type":"string"},"options":{"type":"array","items":{"type":"object","properties":{"label":{"type":"string"},"description":{"type":"string"}},"required":["label","description"]}},"multiSelect":{"type":"boolean"}},"required":["id","header","question","options","multiSelect"]}}},"required":["questions"]}
        }]);
        "thread/start"
    };
    let id = wire.send(method, params).await?;
    let thread = expect(wire, id).await?;
    crate::execution::signal(emit, "thread-ready");
    let thread_id = thread["result"]["thread"]["id"]
        .as_str()
        .ok_or("Codex did not return a thread id")?
        .to_string();
    emit(Activity {
        kind: "session".into(),
        text: thread_id.clone(),
    });
    let mut turn = json!({
        "threadId": thread_id,
        "input": [{"type": "text", "text": input.prompt}],
        "approvalPolicy": if input.access == AccessMode::Ask { "on-request" } else { "never" },
        "approvalsReviewer": "user",
        "cwd": cwd.to_string_lossy(),
        "sandboxPolicy": match input.access {
            AccessMode::Autopilot => json!({"type":"dangerFullAccess"}),
            AccessMode::FileEdits => json!({"type":"workspaceWrite","writableRoots":[cwd.to_string_lossy()],"networkAccess":false,"excludeTmpdirEnvVar":false,"excludeSlashTmp":false}),
            _ => json!({"type":"readOnly"}),
        },
    });
    if !input.effort.is_empty() {
        turn["effort"] = json!(input.effort);
    }
    let id = wire.send("turn/start", turn).await?;
    crate::execution::signal(emit, "request-enqueued");

    // 3. Read until the turn completes. Messages that arrive before the turn id is known are
    // held, so no approval request is handled without its real scope.
    let mut held: Vec<Value> = vec![];
    let mut text = String::new();
    let questions = crate::interactions::Connection::default();
    loop {
        let message = tokio::select! {
            biased;
            _ = cancel.changed() => {
                if let Some(s) = scope.as_ref() {
                    let _ = wire.send("turn/interrupt", json!({"threadId": thread_id, "turnId": s.turn_id})).await;
                }
                return Err("Cancelled".into());
            }
            _ = failed.changed() => {
                return Err("An approval reply could not be delivered, so the turn was stopped. Nothing was retried.".into());
            }
            m = wire.read() => m?,
        };
        let Some(message) = message else {
            return Err("Codex exited before the turn completed".into());
        };
        questions.drain(emit);
        if scope.is_none() {
            if is_response(&message, id) {
                if let Some(e) = message.get("error") {
                    return Err(e["message"]
                        .as_str()
                        .unwrap_or("Codex refused the turn")
                        .to_string());
                }
                let turn_id = message["result"]["turn"]["id"]
                    .as_str()
                    .ok_or("Codex did not return a turn id")?;
                crate::execution::signal(emit, "request-acknowledged");
                *scope = Some(approvals.keeper.start_session(
                    &approvals.chat,
                    Engine::Codex,
                    &thread_id,
                    turn_id,
                    cwd,
                    availability.clone(),
                )?);
                for m in std::mem::take(&mut held) {
                    if let Some(done) = handle(
                        &m,
                        scope,
                        approvals,
                        wire,
                        deliver,
                        &questions,
                        input.access,
                        &mut text,
                        emit,
                    )
                    .await?
                    {
                        return done;
                    }
                }
            } else {
                held.push(message);
            }
            continue;
        }
        if let Some(done) = handle(
            &message,
            scope,
            approvals,
            wire,
            deliver,
            &questions,
            input.access,
            &mut text,
            emit,
        )
        .await?
        {
            return done;
        }
    }
}

/// One protocol message after the scope exists. `Some` ends the turn with its result.
#[allow(clippy::too_many_arguments)]
async fn handle(
    message: &Value,
    scope: &Option<Scope>,
    approvals: &Approvals,
    wire: &mut Wire,
    deliver: &mpsc::Sender<lumen_gatekeeper::Delivery>,
    questions: &crate::interactions::Connection,
    access: AccessMode,
    text: &mut String,
    emit: &mut impl FnMut(Activity),
) -> Result<Option<Result<String, String>>, String> {
    let scope = scope.as_ref().ok_or("No approval scope")?;
    let method = message["method"].as_str().unwrap_or("");
    if message.get("id").is_some() && !method.is_empty() {
        if method == "mcpServer/elicitation/request" {
            let request = crate::connectors::validate_scope(
                &message["params"],
                &scope.provider_session_id,
                &scope.turn_id,
            )
            .and_then(|()| crate::connectors::Request::parse(&message["params"]))
            .and_then(|request| {
                questions
                    .ask_connector(request.clone(), message["id"].to_string())
                    .map(|(activity, receive)| (request, activity, receive))
            });
            match request {
                Ok((request, activity, receive)) => {
                    emit(activity);
                    let out = wire.out.clone();
                    let id = message["id"].clone();
                    tokio::spawn(async move {
                        if let Ok(answers) = receive.await {
                            let result = request
                                .response(&answers)
                                .unwrap_or(json!({"action":"cancel","content":null}));
                            let _ = out.send(json!({"id":id,"result":result})).await;
                        }
                    });
                }
                Err(reason) => {
                    emit(Activity {
                        kind: "connector-status".into(),
                        text: format!("Connector request cancelled: {reason}"),
                    });
                    wire.out
                        .send(
                            json!({"id":message["id"],"result":{"action":"cancel","content":null}}),
                        )
                        .await
                        .map_err(|_| "Codex closed its input")?;
                }
            }
            return Ok(None);
        }
        let dynamic =
            method == "item/tool/call" && message["params"]["tool"] == "lumen_request_user_input";
        if method == "item/tool/requestUserInput" || dynamic {
            if message["params"]["threadId"] != scope.provider_session_id
                || message["params"]["turnId"] != scope.turn_id
            {
                return Err("Codex question belongs to another turn".into());
            }
            let arguments = if dynamic {
                message["params"]["arguments"]
                    .as_str()
                    .and_then(|s| serde_json::from_str::<Value>(s).ok())
                    .unwrap_or_else(|| message["params"]["arguments"].clone())
            } else {
                message["params"].clone()
            };
            let (activity, receive) = questions.ask(
                crate::interactions::codex_questions(&arguments)?,
                message["id"].to_string(),
            )?;
            emit(activity);
            let out = wire.out.clone();
            let id = message["id"].clone();
            tokio::spawn(async move {
                if let Ok(answers) = receive.await {
                    if dynamic {
                        let _=out.send(json!({"id":id,"result":{"success":true,"contentItems":[{"type":"inputText","text":json!({"answers":answers}).to_string()}]}})).await;
                        return;
                    }
                    let answers: serde_json::Map<String, Value> = answers
                        .into_iter()
                        .map(|(id, answers)| (id, json!({"answers":answers})))
                        .collect();
                    let _ = out
                        .send(json!({"id":id,"result":{"answers":answers}}))
                        .await;
                }
            });
            return Ok(None);
        }
        // A server request: approvals go to the panel; anything else is declined.
        match approvals.keeper.request_codex(scope, message) {
            Ok(pending) => {
                if access == AccessMode::Autopilot {
                    approvals.keeper.decide(lumen_gatekeeper::Decision {
                        request_id: pending.request_id.clone(),
                        scope: scope.clone(),
                        action: lumen_gatekeeper::Action::Approve,
                        note: Some("Autopilot: current user authorization".into()),
                    })?;
                }
                let deliver = deliver.clone();
                // Waiting never blocks this reader: cancellations and other approvals keep flowing.
                tokio::spawn(async move {
                    if let Ok(delivery) = pending.wait().await {
                        let _ = deliver.send(delivery).await;
                    }
                });
            }
            Err(reason) => {
                emit(Activity {
                    kind: "tool".into(),
                    text: format!("Declined: {method}\n{reason}"),
                });
                wire.out
                    .send(if matches!(method, "item/commandExecution/requestApproval" | "item/fileChange/requestApproval") {decline(&message["id"])} else {json!({"id":message["id"],"error":{"code":-32601,"message":"Unsupported server request; no permissions granted"}})})
                    .await
                    .map_err(|_| "Codex closed its input")?;
            }
        }
        return Ok(None);
    }
    if OBSERVED.contains(&method) {
        approvals.keeper.observe_codex(scope, message)?;
    }
    if method == "serverRequest/resolved" {
        questions.cancel(&message["params"]["requestId"].to_string());
        questions.drain(emit);
    }
    activity(message, text, emit);
    if method == "turn/completed" {
        let turn = &message["params"]["turn"];
        return Ok(Some(match turn["status"].as_str() {
            Some("completed") if !text.trim().is_empty() => Ok(text.clone()),
            Some("completed") => Err("Codex returned no assistant text".into()),
            Some("interrupted") => Err("Cancelled".into()),
            _ => Err(turn["error"]["message"]
                .as_str()
                .unwrap_or("Codex turn failed")
                .to_string()),
        }));
    }
    Ok(None)
}

async fn expect(wire: &mut Wire, id: u64) -> Result<Value, String> {
    tokio::time::timeout(STEP_TIMEOUT, async {
        while let Some(v) = wire.read().await? {
            if is_response(&v, id) {
                if let Some(e) = v.get("error") {
                    return Err(format!(
                        "unavailable: {}",
                        e["message"].as_str().unwrap_or("Codex refused the request")
                    ));
                }
                return Ok(v);
            }
        }
        Err("unavailable: Codex exited during setup".into())
    })
    .await
    .map_err(|_| "unavailable: Codex app-server did not answer in time".to_string())?
}

